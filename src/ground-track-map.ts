export type GeoPoint = readonly [longitudeDeg: number, latitudeDeg: number];

export interface FootprintMapShape {
  /** Closed polygons in longitude/latitude, each safe to fill on its own. */
  polygons: GeoPoint[][];
  /** Set when the footprint swallows a pole, which needs the polar patch. */
  enclosedPole: "north" | "south" | null;
  crossesAntimeridian: boolean;
  angularRadiusDeg: number;
}

/**
 * The instantaneous coverage footprint, ready to draw on the flat map.
 *
 * The boundary itself is not computed here: it comes from `footprintPoints` in
 * orbit.ts — the same generator, with the same minimum-elevation mask, that the
 * 3-D globe draws — so the two views cannot show different coverage. What this
 * adds is the part that is specific to a flat map.
 *
 * On the globe the trap was flat triangles chording across a sphere. On an
 * equirectangular map the two analogous traps are:
 *
 *   - The antimeridian. A footprint straddling 180 degrees is a single ring in
 *     longitude/latitude, but on the map it is two shapes, one against each
 *     edge. Filled naively it smears a band right across the world.
 *   - The poles. A footprint that swallows a pole has a boundary that winds a
 *     full 360 degrees in longitude and never closes on the map at all. The
 *     filled region is everything between that boundary and the top (or bottom)
 *     edge of the map, so the polygon has to be patched along the pole.
 */
export function footprintMapShape(
  latitudeDeg: number,
  longitudeDeg: number,
  altitudeKm: number,
  minimumElevationDeg = 0,
  segments = 180,
): FootprintMapShape | null {
  if (!Number.isFinite(latitudeDeg) || !Number.isFinite(longitudeDeg) || !Number.isFinite(altitudeKm)) {
    return null;
  }
  if (altitudeKm <= 0) return null;
  const angularRadiusRad = footprintAngularRadius(altitudeKm, minimumElevationDeg);
  if (!Number.isFinite(angularRadiusRad) || angularRadiusRad <= 0) return null;
  const ring = footprintPoints(latitudeDeg, longitudeDeg, altitudeKm, minimumElevationDeg, segments);
  return footprintShapeFromRing(ring, latitudeDeg, (angularRadiusRad * 180) / Math.PI);
}

export function footprintShapeFromRing(
  ring: readonly GeoPoint[],
  centerLatitudeDeg: number,
  angularRadiusDeg = Number.NaN,
): FootprintMapShape | null {
  const cleaned: GeoPoint[] = [];
  for (const [longitude, latitude] of ring) {
    if (!Number.isFinite(longitude) || !Number.isFinite(latitude)) continue;
    cleaned.push([normalizeLongitude(longitude), Math.max(-90, Math.min(90, latitude))]);
  }
  // The generators emit a repeated closing vertex; the ring is treated as
  // closed here, so carrying it would produce a zero-length step.
  while (cleaned.length > 1 && samePoint(cleaned[0]!, cleaned.at(-1)!)) cleaned.pop();
  if (cleaned.length < 3) return null;

  if (Math.abs(longitudeWinding(cleaned)) > 270) {
    // A cap can only reach a pole if its centre is in that hemisphere: the
    // angular radius is strictly under 90 degrees for any real altitude.
    const pole = centerLatitudeDeg >= 0 ? "north" : "south";
    return {
      polygons: [poleCapPolygon(cleaned, pole)],
      enclosedPole: pole,
      crossesAntimeridian: true,
      angularRadiusDeg,
    };
  }

  const polygons = splitRingAtAntimeridian(cleaned);
  return {
    polygons,
    enclosedPole: null,
    crossesAntimeridian: polygons.length > 1,
    angularRadiusDeg,
  };
}

/** Total longitude travelled once round the closed ring, taking each step the short way. */
function longitudeWinding(ring: readonly GeoPoint[]): number {
  let winding = 0;
  for (let index = 0; index < ring.length; index += 1) {
    const from = ring[index]![0];
    const to = ring[(index + 1) % ring.length]![0];
    winding += unwrapLongitudeNear(to, from) - from;
  }
  return winding;
}

/**
 * A pole-enclosing footprint, patched along the pole.
 *
 * Because the boundary crosses every meridian exactly once, it is a function of
 * longitude: sorting the vertices by longitude gives that function directly.
 * The polygon then runs left edge, along the boundary, right edge, up to the
 * pole and back — so the fill is the whole polar region inside the boundary.
 */
function poleCapPolygon(ring: readonly GeoPoint[], pole: "north" | "south"): GeoPoint[] {
  const ordered = [...ring].sort((a, b) => a[0] - b[0]);
  const first = ordered[0]!;
  const last = ordered.at(-1)!;
  const westGap = first[0] + 180;
  const eastGap = 180 - last[0];
  const total = westGap + eastGap;
  // This denominator cannot be zero, and that is worth stating rather than
  // guarding: every longitude here has been through normalizeLongitude, which
  // returns the half-open range [-180, 180) — it maps +180 onto -180. So
  // eastGap is strictly positive and westGap is non-negative. A guard here
  // would be a branch no input can reach, which is exactly the shape of defect
  // this project has shipped before.
  const seamLatitude = last[1] + (first[1] - last[1]) * (eastGap / total);
  const poleLatitude = pole === "north" ? 90 : -90;
  return [
    [-180, seamLatitude],
    ...ordered,
    [180, seamLatitude],
    [180, poleLatitude],
    [-180, poleLatitude],
  ];
}

/**
 * Cuts a closed ring at the antimeridian into one polygon per side of the map.
 * Each piece begins and ends on the same map edge, so closing it draws a
 * straight line down that edge and the fill is correct against it.
 *
 * Exported because the zero-denominator case below is reachable only from a
 * ring that still carries +180 as +180, and a guard nothing can reach is not a
 * guard. Callers inside this module normalize first; the test calls it raw.
 */
export function splitRingAtAntimeridian(ring: readonly GeoPoint[]): GeoPoint[][] {
  const pieces: GeoPoint[][] = [];
  let current: GeoPoint[] = [];
  for (let index = 0; index < ring.length; index += 1) {
    const from = ring[index]!;
    const to = ring[(index + 1) % ring.length]!;
    current.push(from);
    const delta = to[0] - from[0];
    if (Math.abs(delta) <= 180) continue;
    const crossesEast = delta < -180;
    const boundary = crossesEast ? 180 : -180;
    const unwrappedTo = to[0] + (crossesEast ? 360 : -360);
    // The same divide-by-zero that produced NaN coordinates — and a path that
    // silently did not draw — when a polyline stepped from exactly +180 to
    // exactly -180. See tests/world-outlines.test.ts.
    const denominator = unwrappedTo - from[0];
    const fraction = denominator === 0 ? 0 : (boundary - from[0]) / denominator;
    const latitude = interpolate(from[1], to[1], fraction);
    current.push([boundary, latitude]);
    pieces.push(current);
    current = [[-boundary, latitude]];
  }
  if (pieces.length === 0) return [current];
  // The walk began part-way along a piece; its tail joins the first piece's head.
  pieces[0] = [...current, ...pieces[0]!];
  return pieces;
}

function samePoint(a: GeoPoint, b: GeoPoint): boolean {
  return Math.abs(a[0] - b[0]) < 1e-9 && Math.abs(a[1] - b[1]) < 1e-9;
}

