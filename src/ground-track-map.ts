/**
 * Equal degrees per pixel where that is legible. When the track is so thin that
 * an equal-scale zoom would still be a sliver — an inclined geosynchronous
 * analemma is routinely 40 times taller than it is wide — the east-west scale
 * is stretched and the stretch factor is printed on the inset, the way a
 * geological cross-section states its vertical exaggeration.
 */
function compactInsetProjector(
  points: readonly NormalizedGroundTrackPoint[],
  extent: GroundTrackExtent,
  plot: { x: number; y: number; width: number; height: number },
): InsetProjection {
  const unwrapped = unwrapTrack(points);
  const centerLongitude = unwrapped.length === 0
    ? extent.centerLongitudeDeg
    : (Math.min(...unwrapped.map((point) => point.longitudeDeg)) + Math.max(...unwrapped.map((point) => point.longitudeDeg))) / 2;
  const paddedLongitudeSpan = Math.max(extent.longitudeSpanDeg * 1.22, 1e-4);
  const paddedLatitudeSpan = Math.max(extent.latitudeSpanDeg * 1.22, 1e-4);
  const isotropic = Math.max(paddedLongitudeSpan / plot.width, paddedLatitudeSpan / plot.height);

  let longitudeDegreesPerPixel = isotropic;
  const latitudeDegreesPerPixel = isotropic;
  if (paddedLongitudeSpan / isotropic < 10) {
    longitudeDegreesPerPixel = paddedLongitudeSpan / plot.width;
  }
  const exaggeration = longitudeDegreesPerPixel === 0
    ? 1
    : latitudeDegreesPerPixel / longitudeDegreesPerPixel;

  return {
    exaggeration,
    project: (point) => {
      const longitude = unwrapLongitudeNear(point.longitudeDeg, centerLongitude);
      return {
        x: plot.x + plot.width / 2 + (longitude - centerLongitude) / longitudeDegreesPerPixel,
        y: plot.y + plot.height / 2 - (point.latitudeDeg - extent.centerLatitudeDeg) / latitudeDegreesPerPixel,
      };
    },
  };
}

function formatExaggeration(value: number): string {
  if (value >= 100) return String(Math.round(value));
  if (value >= 10) return value.toFixed(0);
  return value.toFixed(1);
}

function filterTicksByProjectedSpacing(
  ticks: readonly NormalizedGroundTrackPoint[],
  projector: (point: NormalizedGroundTrackPoint) => ProjectedPoint,
  minimumHorizontalSpacing = 88,
  minimumVerticalSpacing = 20,
): NormalizedGroundTrackPoint[] {
  const selected: NormalizedGroundTrackPoint[] = [];
  const projected: ProjectedPoint[] = [];
  for (const tick of ticks) {
    const position = projector(tick);
    const overlaps = projected.some((existing) => (
      Math.abs(position.x - existing.x) < minimumHorizontalSpacing
      && Math.abs(position.y - existing.y) < minimumVerticalSpacing
    ));
    if (!overlaps) {
      selected.push(tick);
      projected.push(position);
    }
  }
  return selected;
}

function drawProjectedUtcTicks(
  group: SVGGElement,
  ticks: readonly NormalizedGroundTrackPoint[],
  projector: (point: NormalizedGroundTrackPoint) => ProjectedPoint,
  rightThreshold: number,
  topThreshold: number,
) {
  for (const tick of ticks) {
    const point = projector(tick);
    const nearRight = point.x > rightThreshold;
    const nearTop = point.y < topThreshold;
    group.append(
      svgElement("circle", { cx: String(round(point.x)), cy: String(round(point.y)), r: "2.5", fill: "#45eadb", stroke: "#04101a", "stroke-width": "1.2" }),
      svgElement("text", {
        x: String(round(point.x + (nearRight ? -6 : 6))),
        y: String(round(point.y + (nearTop ? 13 : -5))),
        fill: "#d7edf4",
        "font-family": MONO,
        "font-size": "8.5",
        "text-anchor": nearRight ? "end" : "start",
        style: "paint-order:stroke;stroke:#04101a;stroke-width:3px;stroke-linejoin:round",
      }, formatUtcTick(tick.timeMs)),
    );
  }
}

function drawProjectedCurrentMarker(
  group: SVGGElement,
  current: NormalizedGroundTrackPoint,
  projector: (point: NormalizedGroundTrackPoint) => ProjectedPoint,
  ringRadius: number,
  centerRadius: number,
) {
  const point = projector(current);
  group.append(
    svgElement("circle", { cx: String(round(point.x)), cy: String(round(point.y)), r: String(ringRadius), fill: "none", stroke: "#45eadb", "stroke-width": "1.6", opacity: "0.58" }),
    svgElement("circle", { cx: String(round(point.x)), cy: String(round(point.y)), r: String(centerRadius), fill: "#ffffff", stroke: "#45eadb", "stroke-width": "1.5" }),
  );
}

function unwrapTrack(points: readonly NormalizedGroundTrackPoint[]): NormalizedGroundTrackPoint[] {
  if (points.length === 0) return [];
  const unwrapped: NormalizedGroundTrackPoint[] = [{ ...points[0]! }];
  for (const point of points.slice(1)) {
    const previousLongitude = unwrapped.at(-1)!.longitudeDeg;
    unwrapped.push({
      ...point,
      longitudeDeg: unwrapLongitudeNear(point.longitudeDeg, previousLongitude),
    });
  }
  return unwrapped;
}

function unwrapLongitudeNear(longitudeDeg: number, referenceLongitudeDeg: number): number {
  let longitude = longitudeDeg;
  while (longitude - referenceLongitudeDeg > 180) longitude -= 360;
  while (longitude - referenceLongitudeDeg < -180) longitude += 360;
  return longitude;
}

export function project(longitudeDeg: number, latitudeDeg: number, width: number, height: number): ProjectedPoint {
  const plot = plotRect(width, height);
  return {
    x: plot.x + ((longitudeDeg + 180) / 360) * plot.width,
    y: plot.y + ((90 - latitudeDeg) / 180) * plot.height,
  };
}

function isNormalizedTrack(
  points: readonly GroundTrackPoint[] | readonly NormalizedGroundTrackPoint[],
): points is readonly NormalizedGroundTrackPoint[] {
  return points.length === 0 || "timeMs" in points[0]!;
}

function toTimeMs(value: Date | string | number): number | null {
  const timeMs = value instanceof Date ? value.getTime() : typeof value === "number" ? value : Date.parse(value);
  return Number.isFinite(timeMs) ? timeMs : null;
}

function interpolate(start: number, end: number, fraction: number): number {
  return start + (end - start) * fraction;
}

function formatDuration(minutes: number): string {
  if (!Number.isFinite(minutes)) return "UNKNOWN PERIOD";
  if (minutes < 120) return `${formatNumber(minutes)} min`;
  return `${formatNumber(minutes / 60)} h`;
}

function formatNumber(value: number): string {
  return Number.isInteger(value) ? String(value) : value.toFixed(1);
}

function formatLatitude(latitudeDeg: number): string {
  return `${Math.abs(latitudeDeg).toFixed(2)}°${latitudeDeg >= 0 ? "N" : "S"}`;
}

function formatLongitude(longitudeDeg: number): string {
  return `${Math.abs(longitudeDeg).toFixed(2)}°${longitudeDeg >= 0 ? "E" : "W"}`;
}

function round(value: number): number {
  return Math.round(value * 10) / 10;
}

function wrapWords(text: string, maximumCharacters: number): string[] {
  const lines: string[] = [];
  let line = "";
  for (const word of text.split(" ")) {
    if (line && `${line} ${word}`.length > maximumCharacters) {
      lines.push(line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  if (line) lines.push(line);
  return lines;
}

function svgElement<K extends keyof SVGElementTagNameMap>(
  tagName: K,
  attributes: Readonly<Record<string, string>> = {},
  text?: string,
): SVGElementTagNameMap[K] {
  const element = document.createElementNS(SVG_NAMESPACE, tagName);
  for (const [name, value] of Object.entries(attributes)) element.setAttribute(name, value);
  if (text !== undefined) element.textContent = text;
  return element;
}
