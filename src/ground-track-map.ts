export function formatLongitudeLabel(longitudeDeg: number): string {
  const normalized = normalizeLongitude(longitudeDeg);
  if (normalized === 0) return "0°";
  if (Math.abs(normalized) === 180) return "180°";
  return `${Math.abs(normalized)}°${normalized > 0 ? "E" : "W"}`;
}

export function formatLatitudeLabel(latitudeDeg: number): string {
  if (latitudeDeg === 0) return "0°";
  return `${Math.abs(latitudeDeg)}°${latitudeDeg > 0 ? "N" : "S"}`;
}

/**
 * Meridians and parallels every 30 degrees. The equator and the prime meridian
 * are returned as "principal" so they can be drawn differently from the rest —
 * on a ground-track map you constantly need to know which side of them you are.
 */
export function graticuleLines(stepDeg = GRATICULE_STEP_DEG): GraticuleLine[] {
  const step = Math.max(5, Math.min(90, Math.round(stepDeg)));
  const lines: GraticuleLine[] = [];
  for (let longitude = -180 + step; longitude <= 180 - step; longitude += step) {
    lines.push({
      kind: "meridian",
      degrees: longitude,
      label: formatLongitudeLabel(longitude),
      emphasis: longitude === 0 ? "principal" : "normal",
    });
  }
  for (let latitude = -90 + step; latitude <= 90 - step; latitude += step) {
    lines.push({
      kind: "parallel",
      degrees: latitude,
      label: formatLatitudeLabel(latitude),
      emphasis: latitude === 0 ? "principal" : "normal",
    });
  }
  return lines;
}

