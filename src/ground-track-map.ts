const FOOTPRINT_COLOR = "#f5c96a";

/**
 * The coverage footprint, drawn under the track so the track stays readable.
 * The polygons already handle the seam and the poles; all that is left is to
 * project them.
 */
function drawFootprint(
  group: SVGGElement,
  shape: FootprintMapShape,
  width: number,
  height: number,
) {
  for (const polygon of shape.polygons) {
    if (polygon.length < 3) continue;
    const commands = polygon.map(([longitude, latitude], index) => {
      const point = project(longitude, latitude, width, height);
      return `${index === 0 ? "M" : "L"}${round(point.x)},${round(point.y)}`;
    });
    const path = `${commands.join(" ")} Z`;
    group.append(
      svgElement("path", {
        d: path,
        fill: FOOTPRINT_COLOR,
        "fill-opacity": "0.16",
        stroke: FOOTPRINT_COLOR,
        "stroke-width": "1.2",
        "stroke-opacity": "0.85",
        "stroke-linejoin": "round",
      }),
    );
  }
}

function formatMaskLabel(minimumElevationDeg: number): string {
  return minimumElevationDeg <= 0
    ? "the geometric horizon"
    : `${formatNumber(minimumElevationDeg)}° minimum elevation`;
}

function drawTrack(
  group: SVGGElement,
  segments: readonly (readonly NormalizedGroundTrackPoint[])[],
  width: number,
  height: number,
  phase: "past" | "future",
) {
  for (const segment of segments) {
    if (segment.length < 2) continue;
    const path = segment.map((point, index) => {
      const projected = project(point.longitudeDeg, point.latitudeDeg, width, height);
      return `${index === 0 ? "M" : "L"}${round(projected.x)},${round(projected.y)}`;
    }).join(" ");
    if (phase === "past") {
      group.append(
        svgElement("path", { d: path, fill: "none", stroke: "#04101a", "stroke-width": "6", opacity: "0.72", "stroke-linejoin": "round", "stroke-linecap": "round" }),
        svgElement("path", { d: path, fill: "none", stroke: "#45eadb", "stroke-width": "2.5", "stroke-linejoin": "round", "stroke-linecap": "round" }),
      );
    } else {
      group.append(
        svgElement("path", { d: path, fill: "none", stroke: "#04101a", "stroke-width": "5", opacity: "0.55", "stroke-linejoin": "round", "stroke-linecap": "round" }),
        svgElement("path", { d: path, fill: "none", stroke: "#45eadb", "stroke-width": "1.6", opacity: "0.42", "stroke-dasharray": "5 4", "stroke-linejoin": "round", "stroke-linecap": "round" }),
      );
    }
  }
}

function drawUtcTicks(
  group: SVGGElement,
  ticks: readonly NormalizedGroundTrackPoint[],
  width: number,
  height: number,
) {
  const plot = plotRect(width, height);
  for (const tick of ticks) {
    const point = project(tick.longitudeDeg, tick.latitudeDeg, width, height);
    const nearRight = point.x > plot.x + plot.width - 145;
    const nearTop = point.y < plot.y + 34;
    group.append(
      svgElement("circle", { cx: String(round(point.x)), cy: String(round(point.y)), r: "3", fill: "#45eadb", stroke: "#04101a", "stroke-width": "1.5" }),
      svgElement("text", {
        x: String(round(point.x + (nearRight ? -7 : 7))),
        y: String(round(point.y + (nearTop ? 16 : -7))),
        fill: "#d7edf4",
        "font-family": MONO,
        "font-size": "10",
        "text-anchor": nearRight ? "end" : "start",
        style: "paint-order:stroke;stroke:#04101a;stroke-width:3px;stroke-linejoin:round",
      }, formatUtcTick(tick.timeMs)),
    );
  }
}

