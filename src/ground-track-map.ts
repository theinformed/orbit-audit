/** Mount into a dedicated container and return an update/destroy controller. */
export function mountGroundTrackMap(container: HTMLElement, options: GroundTrackMapOptions) {
  let baseOptions = options;
  let state = initialState(options);

  const root = document.createElement("div");
  root.className = "gtm-root";
  root.style.cssText = "display:flex;flex-direction:column;gap:10px";

  const figure = document.createElement("div");
  figure.className = "gtm-figure";
  root.append(figure);

  const controls = buildTrackControls({
    getBaseOptions: () => baseOptions,
    getState: () => state,
    setState: (next) => {
      state = { ...state, ...next };
      render();
    },
  });
  root.append(controls.element);

  let element = createGroundTrackMap(mapOptions());
  figure.replaceChildren(element);
  container.replaceChildren(root);
  controls.sync();
  announceWindow();

  function mapOptions(): GroundTrackMapOptions {
    return {
      ...baseOptions,
      points: state.points,
      selectedTime: state.selectedMs,
      showFootprint: state.showFootprint,
      window: windowFor(baseOptions, state),
    };
  }

  function announceWindow() {
    const range = trackTimeRange(normalizeGroundTrackPoints(state.points));
    if (!range || !baseOptions.onWindowChange) return;
    baseOptions.onWindowChange({
      startMs: range.startMs,
      endMs: range.endMs,
      centerMs: state.centerMs,
      spanMinutes: state.spanMinutes,
      description: windowDescription(baseOptions, state),
    });
  }

  function render() {
    const next = createGroundTrackMap(mapOptions());
    element.replaceWith(next);
    element = next;
    controls.sync();
    announceWindow();
  }

  return {
    get element(): SVGSVGElement {
      return element;
    },
    get selectedTime(): Date {
      return new Date(state.selectedMs);
    },
    setSelectedTime(time: Date | string | number) {
      const parsed = toTimeMs(time);
      if (parsed === null) return;
      state = { ...state, selectedMs: clampToPoints(parsed, state.points) };
      render();
    },
    update(nextOptions: GroundTrackMapOptions) {
      baseOptions = nextOptions;
      state = initialState(nextOptions);
      controls.rebuild();
      render();
    },
    destroy() {
      controls.destroy();
      root.remove();
    },
  };
}

/**
 * Everything the viewer can change about the drawn window.
 *
 * The window is a centre and a span rather than a start and an end, because
 * that is how the control reads: "show me N orbits around this moment". The
 * default is exactly what the caller supplied, so an untouched dialog draws
 * precisely what it drew before this control existed.
 */
interface TrackViewState {
  points: readonly GroundTrackPoint[];
  centerMs: number;
  spanMinutes: number;
  selectedMs: number;
  showFootprint: boolean;
  /** Which span button is lit, or "custom", or null while showing the default. */
  spanId: string | null;
  /** Set once the viewer moves the centre or changes the span. */
  windowChanged: boolean;
}

function initialState(options: GroundTrackMapOptions): TrackViewState {
  const points = normalizeGroundTrackPoints(options.points);
  const range = trackTimeRange(points);
  const anchorMs = toTimeMs(options.currentTime ?? Date.now()) ?? Date.now();
  const spanMinutes = range && range.endMs > range.startMs
    ? (range.endMs - range.startMs) / 60000
    : (options.periodMinutes ?? 90);
  const centerMs = range ? (range.startMs + range.endMs) / 2 : anchorMs;
  const requested = toTimeMs(options.selectedTime ?? options.currentTime ?? Date.now()) ?? anchorMs;
  return {
    points: options.points,
    centerMs,
    spanMinutes,
    selectedMs: clampToPoints(requested, options.points),
    showFootprint: options.showFootprint ?? false,
    spanId: matchingSpanId(spanMinutes, options.periodMinutes),
    windowChanged: false,
  };
}

function matchingSpanId(spanMinutes: number, periodMinutes?: number | null): string | null {
  const match = trackSpanOptions(periodMinutes)
    .find((option) => Math.abs(option.minutes - spanMinutes) <= option.minutes * 0.02);
  return match?.id ?? null;
}

function windowFor(options: GroundTrackMapOptions, state: TrackViewState): GroundTrackWindow {
  if (!state.windowChanged) return options.window;
  const label = trackSpanOptions(options.periodMinutes)
    .find((option) => option.id === state.spanId)?.label
    ?? formatSpan(state.spanMinutes);
  return {
    kind: "custom-span",
    minutes: state.spanMinutes,
    label,
    geosynchronous: isGeosynchronous(options),
  };
}

function isGeosynchronous(options: GroundTrackMapOptions): boolean {
  if (options.window.kind === "geosynchronous-analemma") return true;
  const period = options.periodMinutes;
  return Number.isFinite(period) && (period as number) >= 1380 && (period as number) <= 1500;
}

/**
 * A complete sentence for a caption above the map. The two untouched cases
 * reproduce what the dialog said before this control existed, with the window's
 * own start and end added, so a caller can hand this straight to its lead line.
 */
function windowDescription(options: GroundTrackMapOptions, state: TrackViewState): string {
  const range = trackTimeRange(normalizeGroundTrackPoints(state.points));
  const bounds = range ? `, ${formatUtcTick(range.startMs)} to ${formatUtcTick(range.endMs)}` : "";
  if (!state.windowChanged && options.window.kind === "orbital-period") {
    return `One ${formatNumber(options.window.periodMinutes)}-minute orbital period`
      + ` projected onto the rotating Earth${bounds}.`;
  }
  if (!state.windowChanged && options.window.kind === "geosynchronous-analemma") {
    return `A ${formatNumber(options.window.hours ?? 24)}-hour Earth-fixed trace${bounds}.`
      + ` ${groundTrackAnnotation(options.window).explanation}`;
  }
  const label = trackSpanOptions(options.periodMinutes).find((option) => option.id === state.spanId)?.label
    ?? formatSpan(state.spanMinutes);
  return `Showing ${label} — ${formatSpan(state.spanMinutes)} of ground track${bounds},`
    + " projected onto the rotating Earth.";
}

function clampToPoints(timeMs: number, points: readonly GroundTrackPoint[]): number {
  const range = trackTimeRange(normalizeGroundTrackPoints(points));
  if (!range) return timeMs;
  return Math.max(range.startMs, Math.min(range.endMs, timeMs));
}

function resolveMarker(
  options: GroundTrackMapOptions,
  points: readonly NormalizedGroundTrackPoint[],
  selectedMs: number,
): { marker: NormalizedGroundTrackPoint | null; altitudeKm: number | null } {
  const anchorMs = toTimeMs(options.currentTime ?? Date.now());
  if (options.sampleAt) {
    const sampled = options.sampleAt(new Date(selectedMs));
    if (sampled) {
      const normalized = normalizeGroundTrackPoints([{ ...sampled, at: selectedMs }])[0];
      if (normalized) {
        return {
          marker: normalized,
          altitudeKm: Number.isFinite(sampled.altitudeKm) ? sampled.altitudeKm! : null,
        };
      }
    }
  }
  // An explicit currentPosition is authoritative only at the time it describes.
  if (options.currentPosition && anchorMs !== null && Math.abs(anchorMs - selectedMs) < 1) {
    const normalized = normalizeGroundTrackPoints([options.currentPosition])[0];
    if (normalized) return { marker: { ...normalized, timeMs: selectedMs }, altitudeKm: null };
  }
  return { marker: interpolateTrackAt(points, selectedMs), altitudeKm: null };
}

