export interface TrackTimeRange {
  startMs: number;
  endMs: number;
}

export function trackTimeRange(points: readonly NormalizedGroundTrackPoint[]): TrackTimeRange | null {
  if (points.length === 0) return null;
  let startMs = points[0]!.timeMs;
  let endMs = points[0]!.timeMs;
  for (const point of points) {
    if (point.timeMs < startMs) startMs = point.timeMs;
    if (point.timeMs > endMs) endMs = point.timeMs;
  }
  return { startMs, endMs };
}

/**
 * Position on the track at an arbitrary time, by straight-line interpolation
 * between the two bracketing samples. Longitude is unwrapped first so a pair
 * straddling the antimeridian interpolates the short way round.
 */
export function interpolateTrackAt(
  points: readonly NormalizedGroundTrackPoint[],
  timeMs: number,
): NormalizedGroundTrackPoint | null {
  if (points.length === 0 || !Number.isFinite(timeMs)) return null;
  if (points.length === 1) return { ...points[0]! };
  const ordered = [...points].sort((a, b) => a.timeMs - b.timeMs);
  if (timeMs <= ordered[0]!.timeMs) return { ...ordered[0]! };
  if (timeMs >= ordered.at(-1)!.timeMs) return { ...ordered.at(-1)! };
  for (let index = 1; index < ordered.length; index += 1) {
    const previous = ordered[index - 1]!;
    const current = ordered[index]!;
    if (timeMs > current.timeMs) continue;
    const span = current.timeMs - previous.timeMs;
    const fraction = span === 0 ? 0 : (timeMs - previous.timeMs) / span;
    const unwrapped = unwrapLongitudeNear(current.longitudeDeg, previous.longitudeDeg);
    return {
      longitudeDeg: normalizeLongitude(interpolate(previous.longitudeDeg, unwrapped, fraction)),
      latitudeDeg: interpolate(previous.latitudeDeg, current.latitudeDeg, fraction),
      timeMs,
    };
  }
  return { ...ordered.at(-1)! };
}

/** Track split into the part already flown and the part still ahead. */
export function splitTrackAtTime(
  points: readonly NormalizedGroundTrackPoint[],
  timeMs: number,
): { past: NormalizedGroundTrackPoint[]; future: NormalizedGroundTrackPoint[] } {
  const ordered = [...points].sort((a, b) => a.timeMs - b.timeMs);
  if (ordered.length === 0) return { past: [], future: [] };
  const boundary = interpolateTrackAt(ordered, timeMs);
  const past = ordered.filter((point) => point.timeMs <= timeMs);
  const future = ordered.filter((point) => point.timeMs >= timeMs);
  if (boundary && past.length > 0 && past.at(-1)!.timeMs !== boundary.timeMs) past.push(boundary);
  if (boundary && future.length > 0 && future[0]!.timeMs !== boundary.timeMs) future.unshift(boundary);
  return { past, future };
}

export type TimeZoneMode = "utc" | "local";

/** The viewer's IANA zone name on its own, e.g. "America/New_York". */
export function localZoneName(): string {
  try {
    return Intl.DateTimeFormat().resolvedOptions().timeZone ?? "";
  } catch {
    return "";
  }
}

export function formatUtcOffset(offsetMinutes: number): string {
  const sign = offsetMinutes < 0 ? "-" : "+";
  const absolute = Math.abs(offsetMinutes);
  return `UTC${sign}${String(Math.floor(absolute / 60)).padStart(2, "0")}:${String(absolute % 60).padStart(2, "0")}`;
}

/** IANA zone name plus the current UTC offset, e.g. "America/New_York · UTC-04:00". */
export function localZoneLabel(at: Date = new Date()): string {
  const zone = localZoneName();
  const offset = formatUtcOffset(-at.getTimezoneOffset());
  return zone ? `${zone} · ${offset}` : offset;
}

export function formatTimeEntry(timeMs: number, zone: TimeZoneMode): string {
  if (!Number.isFinite(timeMs)) return "";
  const date = new Date(timeMs);
  if (zone === "utc") return date.toISOString().slice(0, 16).replace("T", " ");
  const pad = (value: number, size = 2) => String(value).padStart(size, "0");
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())} `
    + `${pad(date.getHours())}:${pad(date.getMinutes())}`;
}

/** How a piece of typed text was actually understood. */
export interface ParsedTimeEntry {
  timeMs: number;
  /** The zone the text was read in: the selected one, or one the text named. */
  zone: TimeZoneMode | "offset";
  /** Human name for that zone, e.g. "UTC" or "America/New_York · UTC-04:00". */
  zoneLabel: string;
  /** True when the calendar date came from the window rather than the text. */
  assumedDate: boolean;
  /** True when the zone came from the selector rather than from the text. */
  assumedZone: boolean;
  /** A plain sentence naming the instant in both zones, and any assumption. */
  reading: string;
}

const MONTH_NAMES = [
  "january", "february", "march", "april", "may", "june",
  "july", "august", "september", "october", "november", "december",
] as const;

interface CalendarParts {
  year: number;
  month: number;
  day: number;
  hour: number;
  minute: number;
  second: number;
  millisecond: number;
}

/**
 * Deliberately tolerant time entry.
 *
 * Accepts, in this order: "now"; a relative offset such as "+90m", "-2h" or
 * "3 hours ago"; the words "today", "yesterday" and "tomorrow", alone or with a
 * time; an ISO-style date with optional T, seconds, fractional seconds and a
 * trailing Z or +/-HH:MM; a US "MM/DD" or "MM/DD/YYYY"; a written month in
 * either order ("7 Aug 2026", "Aug 7"); and a bare clock time meaning that time
 * on the day already shown. Times may be 24-hour or carry am/pm.
 *
 * Anything it cannot read returns null, so the caller says so in place instead
 * of jumping somewhere the viewer did not ask for.
 */
export function parseTimeInput(
  text: string,
  zone: TimeZoneMode,
  referenceMs = Date.now(),
): ParsedTimeEntry | null {
  const trimmed = text.trim().replace(/\s+/g, " ");
  if (!trimmed) return null;
  let body = trimmed.toLowerCase();
  if (!Number.isFinite(referenceMs)) return null;

  if (body === "now") {
    return describe(referenceMs, zone, 0, false, true, `"now"`, false);
  }

  const relative = parseRelativeMinutes(body);
  if (relative !== null) {
    const timeMs = referenceMs + relative * 60000;
    const direction = relative >= 0 ? "after" : "before";
    return describe(timeMs, zone, 0, false, true,
      `${formatSpan(Math.abs(relative))} ${direction} the time on screen`, false);
  }

  // An explicit zone in the text overrides the selector.
  let effective: TimeZoneMode | "offset" = zone;
  let offsetMinutes = 0;
  let assumedZone = true;
  const offsetSuffix = /\s*([+-])(\d{2}):?(\d{2})$/.exec(body);
  if (offsetSuffix && body.includes(":") && /\d\s*[+-]\d{2}:?\d{2}$/.test(body)) {
    offsetMinutes = (offsetSuffix[1] === "-" ? -1 : 1)
      * (Number(offsetSuffix[2]) * 60 + Number(offsetSuffix[3]));
    if (Math.abs(offsetMinutes) > 14 * 60) return null;
    effective = "offset";
    assumedZone = false;
    body = body.slice(0, offsetSuffix.index).trim();
  } else {
    const zoneSuffix = /\s*(z|utc|gmt|zulu)$/.exec(body);
    if (zoneSuffix) {
      effective = "utc";
      assumedZone = false;
      body = body.slice(0, zoneSuffix.index).trim();
      if (!body) return null;
    }
  }

  const reference = zonedParts(referenceMs, effective, offsetMinutes);

  const dayWord = /^(today|yesterday|tomorrow)(?:\s+(?:at\s+)?(.+))?$/.exec(body);
  if (dayWord) {
    const shiftDays = dayWord[1] === "yesterday" ? -1 : dayWord[1] === "tomorrow" ? 1 : 0;
    const clock = dayWord[2] ? parseClock(dayWord[2]) : {
      hour: reference.hour,
      minute: reference.minute,
      second: 0,
      millisecond: 0,
    };
    if (!clock) return null;
    const shifted = zonedParts(referenceMs + shiftDays * 86400000, effective, offsetMinutes);
    // The day word is the date, so nothing about the date is assumed; when no
    // time came with it, the note says where the clock time came from instead.
    return build(
      { ...shifted, ...clock },
      effective, offsetMinutes, assumedZone,
      false,
      `"${dayWord[1]}"${dayWord[2] ? "" : " at the clock time already shown"}`,
    );
  }

  const parsed = parseCalendar(body, reference);
  if (!parsed) return null;
  return build(parsed.parts, effective, offsetMinutes, assumedZone, parsed.assumedDate, parsed.note);

  function build(
    parts: CalendarParts,
    inZone: TimeZoneMode | "offset",
    inOffset: number,
    zoneAssumed: boolean,
    dateAssumed: boolean,
    note: string,
  ): ParsedTimeEntry | null {
    const timeMs = instantFrom(parts, inZone, inOffset);
    if (timeMs === null) return null;
    return describe(timeMs, inZone, inOffset, dateAssumed, zoneAssumed, note);
  }
}

/** Backwards-compatible thin wrapper: just the instant, or null. */
export function parseTimeEntry(
  text: string,
  zone: TimeZoneMode,
  referenceMs = Date.now(),
): number | null {
  return parseTimeInput(text, zone, referenceMs)?.timeMs ?? null;
}

function describe(
  timeMs: number,
  zone: TimeZoneMode | "offset",
  offsetMinutes: number,
  assumedDate: boolean,
  assumedZone: boolean,
  note: string,
  explainZone = true,
): ParsedTimeEntry | null {
  if (!Number.isFinite(timeMs)) return null;
  const zoneLabel = zone === "utc"
    ? "UTC"
    : zone === "offset"
      ? formatUtcOffset(offsetMinutes)
      : localZoneLabel(new Date(timeMs));
  const utcText = `${formatTimeEntry(timeMs, "utc")}Z`;
  const localText = formatTimeEntry(timeMs, "local");
  const localZone = localZoneName() || formatUtcOffset(-new Date(timeMs).getTimezoneOffset());
  const notes = [
    note,
    assumedDate ? "date taken from the window on screen" : "",
    explainZone && assumedZone && zone === "utc" ? "read as UTC" : "",
    explainZone && assumedZone && zone === "local" ? `read in ${localZone}` : "",
    explainZone && !assumedZone ? `zone taken from what you typed: ${zoneLabel}` : "",
  ].filter(Boolean);
  return {
    timeMs,
    zone,
    zoneLabel,
    assumedDate,
    assumedZone,
    reading: `Read as ${utcText} · ${localText} ${localZone}`
      + (notes.length > 0 ? ` (${notes.join("; ")}).` : "."),
  };
}

function parseRelativeMinutes(body: string): number | null {
  const signed = /^([+-])\s*(\d+(?:\.\d+)?)\s*(minutes?|mins?|m|hours?|hrs?|hr|h|days?|d)?$/.exec(body);
  if (signed) {
    const magnitude = relativeMagnitude(Number(signed[2]), signed[3] ?? "m");
    return magnitude === null ? null : (signed[1] === "-" ? -magnitude : magnitude);
  }
  const ago = /^(\d+(?:\.\d+)?)\s*(minutes?|mins?|m|hours?|hrs?|hr|h|days?|d)\s+ago$/.exec(body);
  if (ago) {
    const magnitude = relativeMagnitude(Number(ago[1]), ago[2]!);
    return magnitude === null ? null : -magnitude;
  }
  const ahead = /^in\s+(\d+(?:\.\d+)?)\s*(minutes?|mins?|m|hours?|hrs?|hr|h|days?|d)$/.exec(body);
  if (ahead) return relativeMagnitude(Number(ahead[1]), ahead[2]!);
  return null;
}

function relativeMagnitude(value: number, unit: string): number | null {
  if (!Number.isFinite(value) || value < 0) return null;
  if (/^(hours?|hrs?|hr|h)$/.test(unit)) return value * 60;
  if (/^(days?|d)$/.test(unit)) return value * 1440;
  return value;
}

function parseCalendar(
  body: string,
  reference: CalendarParts,
): { parts: CalendarParts; assumedDate: boolean; note: string } | null {
  const iso = /^(\d{4})[-/](\d{1,2})[-/](\d{1,2})(?:[ t](.+))?$/.exec(body);
  if (iso) {
    const clock = iso[4] ? parseClock(iso[4]) : { hour: 0, minute: 0, second: 0, millisecond: 0 };
    if (!clock) return null;
    return {
      parts: { year: Number(iso[1]), month: Number(iso[2]), day: Number(iso[3]), ...clock },
      assumedDate: false,
      note: "",
    };
  }

  const slash = /^(\d{1,2})\/(\d{1,2})(?:\/(\d{2,4}))?(?:\s+(.+))?$/.exec(body);
  if (slash) {
    const clock = slash[4] ? parseClock(slash[4]) : { hour: 0, minute: 0, second: 0, millisecond: 0 };
    if (!clock) return null;
    const month = Number(slash[1]);
    const day = Number(slash[2]);
    return {
      parts: { year: expandYear(slash[3], reference.year), month, day, ...clock },
      assumedDate: false,
      note: `"${body}" as month/day`,
    };
  }

  const dayFirst = /^(\d{1,2})\s+([a-z]{3,})\.?(?:,)?(?:\s+(\d{4}))?(?:\s+(?:at\s+)?(.+))?$/.exec(body);
  if (dayFirst) {
    const month = monthFromName(dayFirst[2]!);
    if (month !== null) {
      const clock = dayFirst[4] ? parseClock(dayFirst[4]) : { hour: 0, minute: 0, second: 0, millisecond: 0 };
      if (!clock) return null;
      return {
        parts: { year: dayFirst[3] ? Number(dayFirst[3]) : reference.year, month, day: Number(dayFirst[1]), ...clock },
        assumedDate: false,
        note: "",
      };
    }
  }

  const monthFirst = /^([a-z]{3,})\.?\s+(\d{1,2})(?:,)?(?:\s+(\d{4}))?(?:\s+(?:at\s+)?(.+))?$/.exec(body);
  if (monthFirst) {
    const month = monthFromName(monthFirst[1]!);
    if (month !== null) {
      const clock = monthFirst[4] ? parseClock(monthFirst[4]) : { hour: 0, minute: 0, second: 0, millisecond: 0 };
      if (!clock) return null;
      return {
        parts: { year: monthFirst[3] ? Number(monthFirst[3]) : reference.year, month, day: Number(monthFirst[2]), ...clock },
        assumedDate: false,
        note: "",
      };
    }
  }

  const clock = parseClock(body);
  if (clock) {
    return {
      parts: { year: reference.year, month: reference.month, day: reference.day, ...clock },
      assumedDate: true,
      note: "",
    };
  }
  return null;
}

/** A clock time, 24-hour or am/pm. Requires a colon or a meridiem so a bare number is not swallowed. */
function parseClock(text: string): Pick<CalendarParts, "hour" | "minute" | "second" | "millisecond"> | null {
  const match = /^(\d{1,2})(?::(\d{2}))?(?::(\d{2}(?:\.\d+)?))?\s*(am|pm|a\.m\.|p\.m\.)?$/.exec(text.trim());
  if (!match) return null;
  const meridiem = match[4]?.replace(/\./g, "") ?? "";
  if (!match[2] && !meridiem) return null;
  let hour = Number(match[1]);
  const minute = Number(match[2] ?? 0);
  const secondValue = Number(match[3] ?? 0);
  if (meridiem) {
    if (hour < 1 || hour > 12) return null;
    if (meridiem === "am") hour = hour === 12 ? 0 : hour;
    else hour = hour === 12 ? 12 : hour + 12;
  }
  if (hour > 23 || minute > 59 || secondValue >= 61) return null;
  const second = Math.floor(secondValue);
  return { hour, minute, second, millisecond: Math.round((secondValue - second) * 1000) };
}

function monthFromName(name: string): number | null {
  const lower = name.toLowerCase();
  const index = MONTH_NAMES.findIndex((month) => month === lower || month.slice(0, 3) === lower.slice(0, 3));
  return index < 0 ? null : index + 1;
}

function expandYear(text: string | undefined, referenceYear: number): number {
  if (!text) return referenceYear;
  const value = Number(text);
  if (text.length === 4) return value;
  return value < 70 ? 2000 + value : 1900 + value;
}

function zonedParts(timeMs: number, zone: TimeZoneMode | "offset", offsetMinutes: number): CalendarParts {
  if (zone === "local") {
    const date = new Date(timeMs);
    return {
      year: date.getFullYear(), month: date.getMonth() + 1, day: date.getDate(),
      hour: date.getHours(), minute: date.getMinutes(), second: date.getSeconds(), millisecond: 0,
    };
  }
  const date = new Date(timeMs + (zone === "offset" ? offsetMinutes * 60000 : 0));
  return {
    year: date.getUTCFullYear(), month: date.getUTCMonth() + 1, day: date.getUTCDate(),
    hour: date.getUTCHours(), minute: date.getUTCMinutes(), second: date.getUTCSeconds(), millisecond: 0,
  };
}

function instantFrom(parts: CalendarParts, zone: TimeZoneMode | "offset", offsetMinutes: number): number | null {
  const { year, month, day, hour, minute, second, millisecond } = parts;
  if (month < 1 || month > 12 || day < 1 || day > 31) return null;
  if (hour > 23 || minute > 59 || second >= 61) return null;
  if (!Number.isFinite(year)) return null;
  const timeMs = zone === "local"
    ? new Date(year, month - 1, day, hour, minute, second, millisecond).getTime()
    : Date.UTC(year, month - 1, day, hour, minute, second, millisecond) - (zone === "offset" ? offsetMinutes * 60000 : 0);
  if (!Number.isFinite(timeMs)) return null;
  // Reject calendar overflow such as 2026-02-31 rolling into March.
  const check = zonedParts(timeMs, zone, offsetMinutes);
  if (check.day !== day || check.month !== month) return null;
  return timeMs;
}

