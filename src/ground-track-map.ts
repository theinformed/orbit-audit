/**
 * Great-circle separation between two sub-satellite points, in degrees.
 *
 * Deliberately not a longitude difference: near the poles those are enormous
 * and mean almost nothing on the ground, which is exactly where a polar orbit
 * would otherwise be subdivided hardest for no benefit.
 */
export function groundSeparationDeg(
  a: { latitudeDeg: number; longitudeDeg: number },
  b: { latitudeDeg: number; longitudeDeg: number },
): number {
  const toRad = Math.PI / 180;
  const lat1 = a.latitudeDeg * toRad;
  const lat2 = b.latitudeDeg * toRad;
  const dLon = (b.longitudeDeg - a.longitudeDeg) * toRad;
  const cosine = Math.sin(lat1) * Math.sin(lat2)
    + Math.cos(lat1) * Math.cos(lat2) * Math.cos(dLon);
  return Math.acos(Math.max(-1, Math.min(1, cosine))) * (180 / Math.PI);
}

/** The largest gap the track may leave between two drawn points, in degrees. */
export const GROUND_TRACK_MAX_GAP_DEG = 2;

/**
 * Sample a ground track so the DRAWING is even, not the clock.
 *
 * A fixed number of evenly spaced times is right for a circular orbit and
 * badly wrong for an eccentric one, because Kepler's second law says a
 * satellite sweeps equal areas in equal times: near perigee it crosses a great
 * deal of ground per minute, near apogee almost none. Uniform time sampling
 * therefore piles nearly every sample up around apogee and leaves the perigee
 * pass to a handful of points joined by straight chords.
 *
 * Measured on the real catalogue at the previous fixed 180 samples per orbit,
 * comparing the largest gap between consecutive drawn points against the
 * median gap:
 *
 *     ISS (circular LEO)    max  1.9 deg,  median 1.92 deg   -- even
 *     ASBM-1                max  8.0 deg,  median 0.80 deg   -- 10x
 *     IMAGE                 max 19.5 deg,  median 0.92 deg   -- 21x
 *     THEMIS D              max 37.0 deg,  median 1.86 deg   -- 20x
 *
 * Thirty-seven degrees is about 4,100 km of ground drawn as one straight line,
 * which is the visible "kink" in a Molniya or Tundra track and the reason
 * these orbits looked wrong. The propagation was never the problem: the
 * apogee and perigee altitudes SGP4 returns for all of them match the values
 * implied by their own elements to within a few km.
 *
 * So this keeps the uniform pass as a skeleton and then bisects any segment
 * whose endpoints are further apart on the ground than `maxGapDeg`, recursing
 * until the gap closes or the budget runs out. A circular orbit is already
 * under tolerance and costs nothing extra; an eccentric one gets its extra
 * samples exactly where it is moving fastest.
 */
export function sampleGroundTrack(options: {
  /** Centre of the window. */
  at: Date;
  spanMinutes: number;
  /** Evenly spaced samples laid down before any refinement. */
  baseSamples: number;
  sample: (when: Date) => { latitudeDeg: number; longitudeDeg: number } | null;
  maxGapDeg?: number;
  /** Hard ceiling on propagations, so a pathological orbit cannot hang the tab. */
  budget?: number;
}): GroundTrackPoint[] {
  const { at, spanMinutes, baseSamples, sample } = options;
  const maxGapDeg = options.maxGapDeg ?? GROUND_TRACK_MAX_GAP_DEG;
  const budget = options.budget ?? 4000;

  type Sampled = { timeMs: number; latitudeDeg: number; longitudeDeg: number };
  let used = 0;
  const take = (timeMs: number): Sampled | null => {
    if (used >= budget) return null;
    used += 1;
    const state = sample(new Date(timeMs));
    return state ? { timeMs, ...state } : null;
  };

  const coarse: Sampled[] = [];
  for (let index = 0; index <= baseSamples; index += 1) {
    const offsetMinutes = (index / baseSamples - 0.5) * spanMinutes;
    const point = take(at.getTime() + offsetMinutes * 60000);
    if (point) coarse.push(point);
  }
  if (coarse.length < 2) {
    return coarse.map((p) => ({ longitudeDeg: p.longitudeDeg, latitudeDeg: p.latitudeDeg, at: new Date(p.timeMs) }));
  }

  const refined: Sampled[] = [coarse[0]!];
  for (let index = 1; index < coarse.length; index += 1) {
    const left = coarse[index - 1]!;
    const right = coarse[index]!;
    // Iterative rather than recursive: the stack depth is bounded by the
    // budget either way, and a queue makes the budget the only limit.
    const pending: Array<[Sampled, Sampled]> = [[left, right]];
    const inserted: Sampled[] = [];
    while (pending.length > 0 && used < budget) {
      const [a, b] = pending.pop() as [Sampled, Sampled];
      if (groundSeparationDeg(a, b) <= maxGapDeg) continue;
      const midMs = Math.round((a.timeMs + b.timeMs) / 2);
      if (midMs <= a.timeMs || midMs >= b.timeMs) continue;   // out of clock resolution
      const middle = take(midMs);
      if (!middle) continue;
      inserted.push(middle);
      pending.push([a, middle], [middle, b]);
    }
    inserted.sort((a, b) => a.timeMs - b.timeMs);
    refined.push(...inserted, right);
  }
  return refined.map((p) => ({
    longitudeDeg: p.longitudeDeg,
    latitudeDeg: p.latitudeDeg,
    at: new Date(p.timeMs),
  }));
}

export function normalizeLongitude(longitudeDeg: number): number {
  const normalized = ((longitudeDeg + 180) % 360 + 360) % 360 - 180;
  return Object.is(normalized, -0) ? 0 : normalized;
}

export function normalizeGroundTrackPoints(
  points: readonly GroundTrackPoint[],
): NormalizedGroundTrackPoint[] {
  return points.flatMap((point) => {
    const timeMs = toTimeMs(point.at);
    if (!Number.isFinite(point.longitudeDeg) || !Number.isFinite(point.latitudeDeg) || timeMs === null) {
      return [];
    }
    return [{
      longitudeDeg: normalizeLongitude(point.longitudeDeg),
      latitudeDeg: Math.max(-90, Math.min(90, point.latitudeDeg)),
      timeMs,
    }];
  });
}

/**
 * Splits an Earth-fixed track where it crosses the antimeridian. Each side gets
 * an interpolated endpoint at +/-180 degrees, preventing the browser from
 * drawing a false line across the whole map.
 */
export function segmentGroundTrack(
  points: readonly GroundTrackPoint[] | readonly NormalizedGroundTrackPoint[],
): NormalizedGroundTrackPoint[][] {
  const normalized = isNormalizedTrack(points)
    ? points.map((point) => ({ ...point }))
    : normalizeGroundTrackPoints(points as readonly GroundTrackPoint[]);
  if (normalized.length === 0) return [];

  const segments: NormalizedGroundTrackPoint[][] = [[normalized[0]!]];
  for (let index = 1; index < normalized.length; index += 1) {
    const previous = normalized[index - 1]!;
    const current = normalized[index]!;
    const active = segments.at(-1)!;
    const longitudeDelta = current.longitudeDeg - previous.longitudeDeg;

    if (Math.abs(longitudeDelta) <= 180) {
      active.push(current);
      continue;
    }

    const crossesEast = longitudeDelta < -180;
    const unwrappedCurrentLongitude = current.longitudeDeg + (crossesEast ? 360 : -360);
    const boundaryLongitude = crossesEast ? 180 : -180;
    // Guarded because a zero denominator here silently produces NaN
    // coordinates, and an SVG path with NaN in it simply does not draw. The
    // same expression in the offline outline builder did exactly that.
    const denominator = unwrappedCurrentLongitude - previous.longitudeDeg;
    const fraction = denominator === 0
      ? 0
      : (boundaryLongitude - previous.longitudeDeg) / denominator;
    const latitudeDeg = interpolate(previous.latitudeDeg, current.latitudeDeg, fraction);
    const timeMs = interpolate(previous.timeMs, current.timeMs, fraction);

    active.push({ longitudeDeg: boundaryLongitude, latitudeDeg, timeMs });
    segments.push([
      { longitudeDeg: -boundaryLongitude, latitudeDeg, timeMs },
      current,
    ]);
  }
  return segments;
}

export function groundTrackAnnotation(window: GroundTrackWindow): GroundTrackAnnotation {
  if (window.kind === "geosynchronous-analemma") {
    const hours = window.hours ?? 24;
    return {
      label: `${formatNumber(hours)}-HOUR GEOSYNCHRONOUS GROUND TRACK`,
      explanation: "Inclination makes the north-south lobes; eccentricity adds east-west width. A nearly geostationary track collapses toward a point.",
    };
  }
  if (window.kind === "custom-span") {
    const label = window.label ?? formatSpan(window.minutes);
    return {
      label: `${label.toUpperCase()} · ${formatSpan(window.minutes)}`,
      explanation: window.geosynchronous
        ? "Inclination makes the north-south lobes; eccentricity adds east-west width. A nearly geostationary track collapses toward a point."
        : "This is the sub-satellite path on the rotating Earth, not the satellite's closed orbit in inertial space.",
    };
  }
  return {
    label: `ONE ORBIT · ${formatDuration(window.periodMinutes)}`,
    explanation: "This is the sub-satellite path on the rotating Earth, not the satellite's closed orbit in inertial space.",
  };
}

export function selectUtcTickPoints(
  points: readonly NormalizedGroundTrackPoint[],
  requestedCount = 6,
): NormalizedGroundTrackPoint[] {
  if (points.length === 0 || requestedCount <= 0) return [];
  const count = Math.min(points.length, Math.max(2, Math.floor(requestedCount)));
  const selected: NormalizedGroundTrackPoint[] = [];
  const seen = new Set<number>();
  for (let index = 0; index < count; index += 1) {
    const pointIndex = Math.round((index / (count - 1)) * (points.length - 1));
    if (!seen.has(pointIndex)) {
      selected.push(points[pointIndex]!);
      seen.add(pointIndex);
    }
  }
  return selected;
}

export function groundTrackExtent(
  points: readonly NormalizedGroundTrackPoint[],
): GroundTrackExtent | null {
  const unwrapped = unwrapTrack(points);
  if (unwrapped.length === 0) return null;
  const longitudes = unwrapped.map((point) => point.longitudeDeg);
  const latitudes = unwrapped.map((point) => point.latitudeDeg);
  const minimumLongitude = Math.min(...longitudes);
  const maximumLongitude = Math.max(...longitudes);
  const minimumLatitude = Math.min(...latitudes);
  const maximumLatitude = Math.max(...latitudes);
  return {
    centerLongitudeDeg: normalizeLongitude((minimumLongitude + maximumLongitude) / 2),
    centerLatitudeDeg: (minimumLatitude + maximumLatitude) / 2,
    longitudeSpanDeg: maximumLongitude - minimumLongitude,
    latitudeSpanDeg: maximumLatitude - minimumLatitude,
  };
}

/**
 * The inset exists because detail is lost, and detail is lost when the track's
 * footprint on the global map is only a few pixels across. That is a screen
 * test, not a degrees test: SKYTERRA 1's real 24-hour analemma is 0.26 deg of
 * longitude by 10.5 deg of latitude, so it is 40 times taller than it is wide
 * and renders as a bare 0.7 px sliver even though its latitude span is large.
 * An earlier "both spans under 8 deg" rule missed exactly that case.
 */
export function shouldShowCompactGeosynchronousInset(
  points: readonly NormalizedGroundTrackPoint[],
  window: GroundTrackWindow,
  width = DEFAULT_WIDTH,
  height = DEFAULT_HEIGHT,
): boolean {
  const geosynchronous = window.kind === "geosynchronous-analemma"
    || (window.kind === "custom-span" && window.geosynchronous === true);
  if (!geosynchronous || points.length < 2) return false;
  const extent = groundTrackExtent(points);
  if (extent === null) return false;
  const plot = plotRect(width, height);
  const widthPx = (extent.longitudeSpanDeg / 360) * plot.width;
  const heightPx = (extent.latitudeSpanDeg / 180) * plot.height;
  return Math.min(widthPx, heightPx) < 14 || Math.max(widthPx, heightPx) < 30;
}

export function selectGlobalUtcTickPoints(
  points: readonly NormalizedGroundTrackPoint[],
  requestedCount: number,
  width = DEFAULT_WIDTH,
  height = DEFAULT_HEIGHT,
): NormalizedGroundTrackPoint[] {
  const candidates = selectUtcTickPoints(points, requestedCount);
  return filterTicksByProjectedSpacing(
    candidates,
    (point) => project(point.longitudeDeg, point.latitudeDeg, width, height),
  );
}

export function formatUtcTick(timeMs: number): string {
  const iso = new Date(timeMs).toISOString();
  return `${iso.slice(5, 10)} ${iso.slice(11, 16)}Z`;
}

