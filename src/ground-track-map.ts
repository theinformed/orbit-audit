/**
 * The drawing rectangle, forced to 2:1 and centred in whatever box it is given.
 * On an equirectangular map a degree of longitude and a degree of latitude must
 * occupy the same number of pixels; stretching the rectangle to fill an
 * arbitrary container would add a distortion on top of the projection's own.
 */
export function plotRect(width: number, height: number) {
  const availableWidth = width - MAP_MARGIN.left - MAP_MARGIN.right;
  const availableHeight = height - MAP_MARGIN.top - MAP_MARGIN.bottom;
  const plotWidth = Math.max(1, Math.min(availableWidth, availableHeight * 2));
  const plotHeight = plotWidth / 2;
  return {
    x: MAP_MARGIN.left + (availableWidth - plotWidth) / 2,
    y: MAP_MARGIN.top + (availableHeight - plotHeight) / 2,
    width: plotWidth,
    height: plotHeight,
  };
}

