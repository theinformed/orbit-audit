/** Longest window offered, so a stray "9000 orbits" cannot lock the browser up. */
export const MAXIMUM_SPAN_MINUTES = 7 * 24 * 60;
export const MINIMUM_SPAN_MINUTES = 1;

export interface TrackSpanOption {
  id: string;
  /** Button text, e.g. "3 orbits" or "1 orbit · 24 h". */
  label: string;
  /** Second line under the button, e.g. "4.7 h" or "15.2 orbits". */
  detail: string;
  minutes: number;
}

/**
 * The spans offered for a given orbital period.
 *
 * One orbit, three, six, and a day — except that for a geosynchronous
 * spacecraft "one orbit" and "24 hours" are the same window, and offering both
 * would be two buttons that do the same thing. Options within two percent of
 * each other are merged into one button that says so.
 */
export function trackSpanOptions(periodMinutes?: number | null): TrackSpanOption[] {
  const period = Number.isFinite(periodMinutes) && (periodMinutes as number) > 0
    ? (periodMinutes as number)
    : null;
  const candidates: TrackSpanOption[] = [];
  if (period !== null) {
    for (const orbits of [1, 3, 6]) {
      candidates.push({
        id: `orbits-${orbits}`,
        label: orbits === 1 ? "1 orbit" : `${orbits} orbits`,
        detail: formatSpan(period * orbits),
        minutes: period * orbits,
      });
    }
  } else {
    candidates.push({ id: "hours-3", label: "3 hours", detail: "3 h", minutes: 180 });
    candidates.push({ id: "hours-6", label: "6 hours", detail: "6 h", minutes: 360 });
  }
  candidates.push({
    id: "hours-24",
    label: "24 hours",
    detail: period === null ? "1 day" : `${formatNumber(1440 / period)} orbits`,
    minutes: 1440,
  });

  const sorted = candidates
    .filter((option) => option.minutes >= MINIMUM_SPAN_MINUTES && option.minutes <= MAXIMUM_SPAN_MINUTES)
    .sort((a, b) => a.minutes - b.minutes);

  const kept: TrackSpanOption[] = [];
  for (const candidate of sorted) {
    const previous = kept.at(-1);
    if (previous && Math.abs(candidate.minutes - previous.minutes) <= previous.minutes * 0.02) {
      const merged = `${previous.label} · ${candidate.label.replace("24 hours", "24 h")}`;
      previous.detail = `${previous.label} is ${candidate.label.toLowerCase()} for this spacecraft`;
      previous.label = merged;
      continue;
    }
    kept.push({ ...candidate });
  }
  return kept;
}

/**
 * A span typed by hand. Forgiving in the same spirit as the time entry:
 * "90 min", "1.5h", "2 days", "3 orbits", or a bare number meaning minutes.
 */
export function parseSpanEntry(text: string, periodMinutes?: number | null): number | null {
  const trimmed = text.trim().toLowerCase().replace(/\s+/g, " ");
  if (!trimmed) return null;
  const match = /^(\d+(?:\.\d+)?)\s*(orbits?|revs?|revolutions?|minutes?|mins?|m|hours?|hrs?|hr|h|days?|d)?$/
    .exec(trimmed);
  if (!match) return null;
  const value = Number(match[1]);
  if (!Number.isFinite(value) || value <= 0) return null;
  const unit = match[2] ?? "m";
  let minutes: number;
  if (/^(orbits?|revs?|revolutions?)$/.test(unit)) {
    if (!Number.isFinite(periodMinutes) || !(periodMinutes as number > 0)) return null;
    minutes = value * (periodMinutes as number);
  } else if (/^(hours?|hrs?|hr|h)$/.test(unit)) {
    minutes = value * 60;
  } else if (/^(days?|d)$/.test(unit)) {
    minutes = value * 1440;
  } else {
    minutes = value;
  }
  if (minutes < MINIMUM_SPAN_MINUTES || minutes > MAXIMUM_SPAN_MINUTES) return null;
  return minutes;
}

/** Minutes as a phrase a reader can size up at a glance. */
export function formatSpan(minutes: number): string {
  if (!Number.isFinite(minutes)) return "unknown span";
  if (minutes < 120) return `${formatNumber(minutes)} min`;
  if (minutes < 2880) return `${formatNumber(minutes / 60)} h`;
  return `${formatNumber(minutes / 1440)} d`;
}

/**
 * Samples across the window. Spacing is held near half a minute for short
 * windows and stretched for long ones, capped so a week of track cannot turn
 * into an unbounded number of SGP4 calls.
 */
export function trackSampleCount(spanMinutes: number): number {
  if (!Number.isFinite(spanMinutes) || spanMinutes <= 0) return 240;
  return Math.max(240, Math.min(2000, Math.round(spanMinutes * 2)));
}

export function sampleTrackWindow(
  sampleAt: (time: Date) => GroundTrackSample | null,
  centerMs: number,
  spanMinutes: number,
): GroundTrackPoint[] {
  const span = Math.max(MINIMUM_SPAN_MINUTES, Math.min(MAXIMUM_SPAN_MINUTES, spanMinutes));
  const samples = trackSampleCount(span);
  const points: GroundTrackPoint[] = [];
  for (let index = 0; index <= samples; index += 1) {
    const offsetMinutes = (index / samples - 0.5) * span;
    const at = new Date(centerMs + offsetMinutes * 60000);
    const state = sampleAt(at);
    if (!state) continue;
    points.push({ longitudeDeg: state.longitudeDeg, latitudeDeg: state.latitudeDeg, at });
  }
  return points;
}

