/**
 * The mechanism library: six short animations of how the thing actually works.
 *
 * A graphic carries a mechanism better than a paragraph does. These are the
 * six places where that bites hardest — the steps the Learn track had been
 * asserting in words because no camera has ever filmed them and no instrument
 * returns them as a picture.
 *
 * WHAT THEY ARE, AND WHAT THEY ARE NOT. Every one is drawn with Manim from the
 * geometry or the formula named on the frame. None of them is generated by an
 * image or video model, and none of them is data. They are `schematic` in this
 * site's own vocabulary — "drawn to explain a shape, not to report a value" —
 * and that word is burned into the bottom-left corner of every frame as well as
 * printed in the figcaption, so the class survives being screenshotted or
 * downloaded. Nobody mistakes a labelled vector diagram for a photograph, which
 * is exactly why this genre is safe where generated video is not.
 *
 * WHERE THE NUMBERS COME FROM. A schematic may still carry real numbers, and
 * three of these do. Each such figure names its source here and on the frame:
 * the eccentric-dipole offset is this repository's own arithmetic in
 * src/eccentric-dipole.ts, the Chapman curve is Chapman's 1931 production
 * function evaluated live rather than traced, and the orbital speeds and
 * periods are circular-orbit arithmetic on mu = 398 600 km^3/s^2.
 *
 * TYPOGRAPHY AND COLOUR. The frames use the site's own two typefaces — the
 * exact woff2 files in src/fonts, converted to TTF for Pango — and the palette
 * tokens from src/styles.css. Nothing here is Manim's default blue-on-black.
 *
 * NARRATION. Each clip carries a voice track, muxed into the mp4 rather than
 * served as a parallel mp3 the page would have to keep in sync. It is Sean's
 * own professionally cloned voice through tools/narrate.py, and every line was
 * proved by transcribing the rendered audio back and comparing it to the
 * script. The rule the writing follows is the one thing worth knowing about
 * it: the voice says the point the caption is making, extends it with what the
 * caption had no room for, and picks up the previous line's last idea BY NAME.
 * Thirty-six lines over six and a half minutes of picture, and the voice is on
 * 78 to 87 percent of every clip.
 *
 * THE OPPOSITE RULE USED TO BE WRITTEN HERE and it is retired. It read: the
 * captions are burned into the frame and are good, so the voice never reads
 * them; where there is nothing to add it says nothing; the rest is silence on
 * purpose. It was followed exactly, and it produced fifteen lines for
 * seventy-nine caption beats - speech on 18 to 37 percent of each clip, with
 * the voice first arriving 40.8 s into a 79.1 s clip. Sean watched one and
 * reported his voice missing from the videos. Nothing was broken; the design
 * was wrong. Do not reinstate it: if a beat has nothing worth saying, the
 * answer is a shorter clip, not a silent one.
 *
 * The captions stay regardless - they are the accessibility floor for a deaf
 * reader, they are what makes a clip work with the sound off, and they survive
 * a screenshot because they are burned in. The spoken words are ALSO carried
 * here as `narration` and printed as a closed transcript under each figure,
 * because everything the voice adds is by construction not on the frame.
 *
 * The clips are no longer `muted` and no longer `loop`: a muted narration is
 * not a narration, and a voice track that restarts forever is an irritation
 * rather than a feature. They stay `controls` + `preload="none"`, so nothing is
 * fetched and nothing is heard until the reader presses play.
 *
 * PAGE WEIGHT. Every video is `preload="none"`, so a visit to a page carrying
 * one of these downloads the poster and nothing else until the reader presses
 * play. Sources are under tools/mechanism-animations/.
 */

/**
 * Media under `media/mechanisms/`, resolved the way src/event-replay.ts
 * resolves `media/` — a `new URL` against import.meta.url, which Vite turns
 * into a hashed emit under dist/assets. That matters: deploy/web.Dockerfile
 * copies dist/assets and names every other file explicitly, so an asset that
 * does not go through the bundler is not served at all.
 */
