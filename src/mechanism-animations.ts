/**
 * The library's own size, in clips and in seconds.
 *
 * The weather index's mechanisms door carried "6 clips · 6 min 32 s" as
 * hand-written copy. On 2026-08-27 the clips were re-rendered longer — the
 * narration went from fifteen spoken lines to forty-four — and the door did not
 * move, so for as long as that lasted it under-reported its own library by
 * forty seconds. Correcting the constant would go stale again on the next
 * re-render, so the door reads these instead.
 */
export const MECHANISM_LIBRARY_SECONDS = MECHANISM_ANIMATIONS.reduce((total, m) => {
  // "mm:ss", per MechanismAnimation.runtime. A malformed entry propagates NaN
  // rather than being coerced to zero: a door that quietly under-counts its own
  // library is the exact failure this constant exists to end.
  const parts = m.runtime.split(":");
  return total + Number(parts[0]) * 60 + Number(parts[1]);
}, 0);

/** The total runtime as a door prints it: "7 min 12 s". */
export function mechanismLibraryRuntime(): string {
  const minutes = Math.floor(MECHANISM_LIBRARY_SECONDS / 60);
  return `${minutes} min ${MECHANISM_LIBRARY_SECONDS % 60} s`;
}

const byId = new Map(MECHANISM_ANIMATIONS.map((m) => [m.id, m]));

/** Look one up, for a page that wants to embed a single figure. */
export function mechanismAnimation(id: string): MechanismAnimation | undefined {
  return byId.get(id);
}

/**
 * One figure, in the markup the layer pages already use, so it inherits
 * `.layer-figure` / `.layer-video` / `.layer-figcaption` from src/styles.css
 * rather than introducing a second treatment for the same object.
 */
export function mechanismFigure(id: string): string {
  const m = byId.get(id);
  if (!m) return "";
  return `
    <figure class="layer-figure" id="mechanism-${m.id}">
      <div class="learning-video-scroll" tabindex="0" role="group" aria-label="Video; scroll sideways when enlarged"><video
        class="layer-video"
        src="${clip(m.stem)}"
        poster="${poster(m.stem)}"
        controls
        playsinline
        preload="none"
        aria-label="${m.title}: ${m.evidenceLabel}"
      ><track kind="captions" srclang="en" label="English — complete narration" src="${captions(m.stem)}" default></video></div>
      <button type="button" class="figure-full-size" data-video-enlarge aria-pressed="false">Enlarge video to original size</button>
      <figcaption class="layer-figcaption">
        <p class="layer-evidence">${evidenceBadge(m.evidence)}<span class="layer-status-note">${m.evidenceLabel}</span></p>
        <div class="mechanism-caption-prose"><p>${m.lead}</p>${sourceNote(m)}${legacyMediaNote()}${transcript(m)}</div>
      </figcaption>
    </figure>`;
}

/**
 * The spoken lines, closed by default.
 *
 * Native synchronized captions carry the full narration during playback.
 * This separate transcript also supports reading, searching and review without
 * playing the movie; the on-frame summaries alone do not contain every word.
 */
function transcript(m: MechanismAnimation): string {
  const spoken = mechanismNarration(m.stem);
  if (!spoken.length) return "";
  const lines = spoken.map((t) => `<li>${t}</li>`).join("");
  return `<details class="mechanism-transcript"><summary>Narration transcript \u00b7 ${spoken.length} lines</summary><ol>${lines}</ol></details>`;
}

function sourceNote(m: MechanismAnimation): string {
  const references: Record<string, SourceId[]> = {
    'dayside-reconnection': ['dungey'], 'chapman-layer': ['chapman'],
    'hf-skip-blackout': ['drap'], 'trapped-motion': ['convection', 'dst'],
    'eccentric-dipole-saa': ['igrf', 'local'], 'drag-orbit-decay': ['local'],
  };
  return m.sources.map((s) => `<p><em>${s}</em></p>`).join("")
    + `<p class="method-citation">Sources: ${sourceLinks(references[m.id] ?? [])}</p>`;
}

/**
 * The whole library, as a section for the space-weather learning track.
 *
 * Deliberately not a wall of text: each card is a question and two sentences,
 * because the animation is the explanation and the prose is only there to say
 * which question it answers.
 */
export function mechanismLibrarySection(): string {
  return `
    <section class="method-section" id="mechanism-library" aria-labelledby="mechanism-library-title">
      <div class="method-section-head">
        <p class="section-kicker">MECHANISM LIBRARY · ${countWordCap(MECHANISM_ANIMATIONS.length).toUpperCase()} THINGS NO CAMERA HAS FILMED</p>
        <h2 id="mechanism-library-title">Watch the mechanism instead of reading it</h2>
        <p>${countWordCap(MECHANISM_ANIMATIONS.length)} short animations of the steps this site had been asserting in words. Every one is drawn from the geometry or the formula named on the frame, the teaching geometry is <strong>schematic</strong>. Trapped motion is a composite: its closing Kyoto Dst trace is observed, while the motion is schematic. None of them is generated video.</p>
      </div>
      ${MECHANISM_ANIMATIONS.map(mechanismCard).join("")}
    </section>`;
}

function mechanismCard(m: MechanismAnimation): string {
  return `
    <article class="mechanism-entry">
      <p class="section-kicker">MECHANISM ${m.index} · ${m.runtime}</p>
      <h3>${m.title}</h3>
      <p class="mechanism-question">${m.question}</p>
      ${mechanismFigure(m.id)}
    </article>`;
}
