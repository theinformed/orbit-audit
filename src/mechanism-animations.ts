const clip = (stem: string) => new URL(`../media/mechanisms/${stem}.mp4`, import.meta.url).href;
const captions = (stem: string) => new URL(`../media/mechanisms/${stem}.vtt`, import.meta.url).href;
const poster = (stem: string) => new URL(`../media/mechanisms/${stem}.jpg`, import.meta.url).href;

export type MechanismAnimation = {
  id: string;
  index: string;
  /** Short title, as it reads on the frame. */
  title: string;
  /** The one-line question the piece answers. */
  question: string;
  /** Two sentences. Anything longer belongs in the animation. */
  lead: string;
  /** Composite when an observed trace accompanies the schematic motion. */
  evidence: "schematic" | "composite";
  evidenceLabel: string;
  /** Runtime, mm:ss. */
  runtime: string;
  /** Named sources for any real number the animation carries. Empty is honest. */
  sources: string[];
  /** File stem under media/mechanisms/; expects <stem>.mp4 and <stem>.jpg. */
  stem: string;
};

/**
 * THE TRANSCRIPT IS DERIVED, NOT TRANSCRIBED.
 *
 * This used to be a `narration: string[]` field on each entry below, hand-copied
 * from narration/mechanisms.json. On 2026-08-27 the clips went from fifteen
 * spoken lines to forty-four and the copy stayed at fifteen, so for as long as
 * that lasted a reader who cannot hear was being given a third of what a
 * hearing reader got -- silently, and with the page still looking correct.
 * That is the exact failure the transcript exists to prevent.
 *
 * So the words come from the script the audio was rendered from, and the ORDER
 * comes from narration-alignment.json, which is the muxer's own record of what
 * it placed where. Neither can drift from the audio without the build changing.
 */
const SPOKEN_TEXT = new Map<string, string>(
  (narrationScript as { lines: { id: string; text: string }[] }).lines
    .map((line) => [line.id, line.text] as const),
);

const NARRATION_BY_STEM = new Map<string, string[]>(
  (narrationAlignment as { stem: string; lines: { id: string }[] }[]).map((clip) => [
    clip.stem,
    clip.lines.map((placed) => SPOKEN_TEXT.get(placed.id)).filter((t): t is string => !!t),
  ]),
);

/** The spoken lines for one clip, in the order they are spoken. */
export function mechanismNarration(stem: string): string[] {
  return NARRATION_BY_STEM.get(stem) ?? [];
}

